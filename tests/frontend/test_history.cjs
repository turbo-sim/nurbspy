// History stores completed edits, not evaluation previews or navigation changes.
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
    const {EditHistory}=await import(pathToFileURL(path.resolve(__dirname,'../../src/nurbspy/web_assets/history.js')).href);
    let busy=false,fail=false;const restored=[];
    const history=new EditHistory({busy:()=>busy,restore:async(...args)=>{if(fail)throw Error('rejected');restored.push(args);}});
    const model=x=>({control_points:[[x],[0],[0]],weights:[1]});
    const selection={indices:[0],active:0};
    history.begin('surface',model(0),selection);
    assert.equal(history.canUndo,false);assert.equal(history.begin('surface',model(1),selection),false);
    history.finish(model(3));assert.equal(history.past.length,1);
    busy=true;assert.equal(await history.travel(),false);busy=false;
    await history.travel();assert.deepEqual(restored.at(-1),['surface',model(0),selection]);
    assert.equal(history.canRedo,true);await history.travel(true);assert.deepEqual(restored.at(-1)[1],model(3));
    console.log('PASS One completed edit supports undo/redo and cannot replay while Python is busy');
    history.begin('curve',model(2),selection);history.finish(model(4));
    fail=true;await assert.rejects(()=>history.travel(),/rejected/);fail=false;
    assert.equal(history.past.length,2);assert.equal(history.future.length,0);assert.equal(history.restoring,false);
    await history.travel();assert.equal(restored.at(-1)[0],'curve');
    await history.travel();assert.equal(restored.at(-1)[0],'surface');
    history.begin('surface',model(0),selection);history.finish(model(1));
    assert.equal(history.future.length,0);
    console.log('PASS Global object order, rejected restores, and redo-branch replacement preserve history');
    history.begin('surface',model(1),selection);history.finish(model(1));assert.equal(history.past.length,1);
    history.begin('surface',model(1),selection);history.cancel();assert.equal(history.past.length,1);
    const limited=new EditHistory({limit:2});
    for(let i=0;i<5;i++){limited.begin('curve',model(i),selection);limited.finish(model(i+1));}
    assert.equal(limited.past.length,2);
    const tiny=new EditHistory({bytes:10});tiny.begin('curve',model(0),selection);tiny.finish(model(1));assert.equal(tiny.past.length,0);
    console.log('PASS No-op/cancelled edits add no history and retained snapshots have count/memory bounds');
    const {EditingControls}=await import(pathToFileURL(path.resolve(__dirname,'../../src/nurbspy/web_assets/editing.js')).href);
    const shortcuts=Object.create(EditingControls.prototype),actions=[];
    shortcuts.owner={};shortcuts.travel=redo=>actions.push(redo);
    const key=(key,target,extra={})=>({key,target:{tagName:target},ctrlKey:true,preventDefault(){this.prevented=true;},stopPropagation(){},...extra});
    const input=key('z','INPUT');assert.equal(shortcuts.keyDown(input),false);assert.equal(input.prevented,undefined);
    const editable=key('z','DIV');editable.target.isContentEditable=true;assert.equal(shortcuts.keyDown(editable),false);
    shortcuts.keyDown(key('z','CANVAS'));shortcuts.keyDown(key('z','CANVAS',{ctrlKey:false,metaKey:true,shiftKey:true}));
    assert.deepEqual(actions,[undefined,true]);
    console.log('PASS Editor shortcuts respect native input undo and accept macOS Command modifiers');
    let complete;
    const delayed=new EditHistory({restore:()=>new Promise(resolve=>complete=resolve)});
    delayed.begin('curve',model(0),selection);delayed.finish(model(1));
    const replay=delayed.travel();assert.equal(delayed.restoring,true);
    assert.equal(await delayed.travel(),false);assert.equal(delayed.begin('curve',model(2),selection),false);
    complete();await replay;assert.equal(delayed.canRedo,true);
    console.log('PASS A delayed restore blocks overlapping replay and new geometry transactions');
    console.log('5 history checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
