"""Preview an oloid, then export overview, line-following and combined animations.

Two exact NURBS circles define smooth cubic ruled patches. This illustrates revealing
and removing the generated surface, rather than flattening it into a planar net.
Settings are globals below; no sys.path manipulation or command-line flags.
"""

from functools import lru_cache
from pathlib import Path
from time import perf_counter
import numpy as np
from PIL import Image
from scipy.interpolate import BSpline, make_interp_spline
import nurbspy as nrb


# Main switches: close the visualizer to begin export, or disable export to just explore.
EXPORT_ANIMATION = True
SHOW_VISUALIZER = True

FPS = 30
LOOP_SECONDS = 40.0
DEVELOPMENT_CYCLES = 2
CAMERA_ORBITS = 3
HOLD_SECONDS = 1.0  # Pause the line at each fully formed and line-only state.
FOLLOW_DISTANCE = 8.0
FOLLOW_ANGLE_DEGREES = 15.0
IMAGE_WIDTH = 1000
IMAGE_HEIGHT = 750
GIF_WIDTH = 800
GIF_HEIGHT = 600
FIT_TOLERANCE = 1e-5  # Maximum checked boundary error, relative to the unit radius.
RESOLUTION = 70
OUTPUT = Path(__file__).resolve().parent / "output"


def boundaries(parameter, sign):
    """Analytical ruling endpoints at normalized sweep parameters in [0, 1]."""
    parameter = np.atleast_1d(np.asarray(parameter, dtype=float))
    theta = np.pi - sign * 2 * np.pi / 3 * np.cos(np.pi * parameter)
    cosine, sine = np.cos(theta), np.sin(theta)
    phi_cosine = np.clip(cosine / (1 - cosine), -1, 1)
    seam = (parameter == 0) | (parameter == 1)
    phi_cosine[seam] = 1.
    first = np.stack((cosine - .5, sine, np.zeros_like(theta)))
    second = np.stack((.5 + phi_cosine, np.zeros_like(theta), sign * np.sqrt(1 - phi_cosine ** 2)))
    # Both patches share these exact endpoints, including the closing seam.
    first[0, seam] = 0.
    first[1, seam] = sign * (1 - 2 * parameter[seam]) * np.sqrt(3) / 2
    return first, second


@lru_cache(maxsize=4)
def fitted_boundaries(tolerance):
    """Fit both boundary curves together so their cubic knots stay compatible."""
    if not np.isfinite(tolerance) or tolerance <= 0:
        raise ValueError("FIT_TOLERANCE must be finite and positive")
    check = np.linspace(0., 1., 8193)
    exact = np.concatenate(boundaries(check, 1), axis=0).T
    nodes = np.linspace(0., 1., 9)
    for _ in range(12):
        points = np.concatenate(boundaries(nodes, 1), axis=0).T
        spline = make_interp_spline(nodes, points, k=3)
        errors = np.linalg.norm((spline(check) - exact).reshape(-1, 2, 3), axis=2).max(axis=1)
        maximum = float(errors.max())
        if maximum <= tolerance:
            return spline, maximum
        # Add interpolation nodes only where the independent check exceeds tolerance.
        intervals = np.unique(np.clip(np.searchsorted(nodes, check[errors > tolerance], side="right") - 1,
                                      0, len(nodes) - 2))
        nodes = np.sort(np.r_[nodes, (nodes[intervals] + nodes[intervals + 1]) / 2])
    raise ValueError("Boundary fit did not reach FIT_TOLERANCE; choose a larger tolerance")


def boundary_spline(sign):
    spline, _ = fitted_boundaries(FIT_TOLERANCE)
    if sign == 1:
        return spline
    # Traverse the lower patch backwards and reflect it through z=0.
    controls = spline.c[::-1].copy()
    controls[:, 5] *= -1
    return BSpline(1 - spline.t[::-1], controls, spline.k)


def patch(fraction, sign):
    """Reveal a subdomain of the fitted surface without refitting its geometry."""
    fraction = float(np.clip(fraction, 0., 1.))
    spline = boundary_spline(sign)
    if fraction == 0:
        controls = np.repeat(spline.c[:1], 4, axis=0)
        knots = np.r_[np.zeros(4), np.ones(4)]
    elif fraction < 1:
        multiplicity = np.count_nonzero(spline.t == fraction)
        trimmed = spline.insert_knot(fraction, m=4 - multiplicity)
        stop = np.searchsorted(trimmed.t, fraction, side="right")
        knots = trimmed.t[:stop] / fraction
        controls = trimmed.c[:len(knots) - 4]
    else:
        controls, knots = spline.c, spline.t
    first = nrb.NurbsCurve(controls[:, :3].T, degree=3, knots=knots)
    second = nrb.NurbsCurve(controls[:, 3:].T, degree=3, knots=knots)
    return nrb.NurbsSurfaceRuled(first, second).NurbsSurface


def generating_line(fraction, sign):
    endpoints = boundary_spline(sign)(fraction).reshape(2, 3).T
    return nrb.NurbsCurve(endpoints, degree=1)


def make_figure():
    figure = nrb.Figure(title="Oloid generated by a moving straight line", resolution=RESOLUTION)
    plain = dict(control_points=False, control_polygon=False)
    x_axis, y_axis, z_axis = np.eye(3)
    circles = [nrb.CircularArc([-.5, 0, 0], x_axis, y_axis, 1., 0., 2 * np.pi).NurbsCurve,
               nrb.CircularArc([.5, 0, 0], x_axis, z_axis, 1., 0., 2 * np.pi).NurbsCurve]
    for name, circle in zip(("circle A", "circle B"), circles):
        figure.add(circle, name=name, display={**plain, "geometry_color": "#555555"})
    figure.add(patch(1, 1), name="upper sweep", display=plain)
    figure.add(patch(1, -1), name="lower sweep", display=plain)
    figure.add(generating_line(0., 1),
               name="generating line", visible=False,
               display={**plain, "geometry_color": "#ff3300", "control_color": "#ff3300",
                        "control_points": True, "control_polygon": True})
    figure.set_camera(position=[3.5, -5., 3.], target=[.2, 0, 0], up=[0, 0, 1])
    return figure


def update_surface(figure, progress, *, show_generator=True):
    progress = float(np.clip(progress, 0., 1.))
    upper, lower = min(2 * progress, 1), max(2 * progress - 1, 0)
    figure.update("upper sweep", geometry=patch(upper, 1), visible=upper > 0)
    figure.update("lower sweep", geometry=patch(lower, -1), visible=lower > 0)
    fraction, sign = sweep_position(progress)
    figure.update("generating line", geometry=generating_line(fraction, sign), visible=show_generator)


def sweep_position(progress):
    progress = float(np.clip(progress, 0., 1.))
    return (2 * progress, 1) if progress < .5 else (2 * progress - 1, -1)


def total_seconds():
    return LOOP_SECONDS


def phase_at(seconds):
    seconds = float(np.clip(seconds, 0., total_seconds()))
    cycle_seconds = total_seconds() / DEVELOPMENT_CYCLES
    motion_seconds = (cycle_seconds - 2 * HOLD_SECONDS) / 2
    local = seconds % cycle_seconds
    cycle = min(int(seconds / cycle_seconds) + 1, DEVELOPMENT_CYCLES)
    if local < HOLD_SECONDS:
        progress, phase = 0., "Hold line"
    elif local < HOLD_SECONDS + motion_seconds:
        fraction = (local - HOLD_SECONDS) / motion_seconds
        progress, phase = .5 * (1 - np.cos(np.pi * fraction)), "Develop"
    elif local < 2 * HOLD_SECONDS + motion_seconds:
        progress, phase = 1., "Hold full oloid"
    else:
        fraction = (local - 2 * HOLD_SECONDS - motion_seconds) / motion_seconds
        progress, phase = .5 * (1 + np.cos(np.pi * fraction)), "Undevelop"
    return progress, f"{phase} {cycle}/{DEVELOPMENT_CYCLES}", True


def orbit_camera(figure, seconds, camera):
    seconds = float(np.clip(seconds, 0., total_seconds()))
    if seconds == 0 or seconds == total_seconds():
        figure.set_camera(**camera)
        return
    target = np.asarray(camera["target"], dtype=float)
    relative = np.asarray(camera["position"], dtype=float) - target
    angle = 2 * np.pi * CAMERA_ORBITS * seconds / total_seconds()
    rotation = np.array([[np.cos(angle), -np.sin(angle), 0], [np.sin(angle), np.cos(angle), 0], [0, 0, 1]])
    position = target + rotation @ relative
    up = rotation @ np.asarray(camera["up"])
    figure.set_camera(**{**camera, "position": position.tolist(), "up": up.tolist(), "projection": "3d"})


def following_camera(figure, progress):
    """Keep the active ruling broadside and in front of the generated surface."""
    fraction, sign = sweep_position(progress)
    line = generating_line(fraction, sign).P
    midpoint = line.mean(axis=1)
    direction = line[:, 1] - line[:, 0]
    direction /= np.linalg.norm(direction)
    theta = np.pi - sign * 2 * np.pi / 3 * np.cos(np.pi * fraction)
    cosine, sine = np.cos(theta), np.sin(theta)
    # This outward supporting-plane normal is continuous across both seams.
    # Using geometry instead of time derivatives avoids flips on reversal/holds.
    normal = np.array([cosine, sine, sign * np.sqrt(max(0., 1 - 2 * cosine))])
    normal -= np.dot(normal, direction) * direction
    normal /= np.linalg.norm(normal)
    behind = np.cross(normal, direction)
    angle = np.deg2rad(FOLLOW_ANGLE_DEGREES)
    view = np.cos(angle) * normal + np.sin(angle) * behind
    figure.set_camera(position=(midpoint + FOLLOW_DISTANCE * view).tolist(),
                      target=midpoint.tolist(), up=[0., 0., 1.], projection="3d", zoom=1., fov=38.)


def animation_frames(figure, camera, count, *, view="overview"):
    if view not in ("overview", "following"):
        raise ValueError("view must be 'overview' or 'following'")
    previous = None
    for seconds in np.linspace(0., total_seconds(), count):
        progress, _, generator = phase_at(seconds)
        if (progress, generator) != previous:
            update_surface(figure, progress, show_generator=generator)
            previous = progress, generator
        if view == "overview":
            orbit_camera(figure, float(seconds), camera)
        else:
            following_camera(figure, progress)
        yield figure


def _clock(seconds):
    minutes, seconds = divmod(max(0, int(seconds)), 60)
    return f"{minutes:02d}:{seconds:02d}"


def combine_frames(left, right, directory):
    """Join corresponding PNGs without changing either panel's framing or timing."""
    if not left or len(left) != len(right):
        raise ValueError("Both views need the same nonzero number of frames")
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    paths = []
    for index, (a_path, b_path) in enumerate(zip(left, right)):
        with Image.open(a_path) as a, Image.open(b_path) as b:
            if a.size != b.size:
                raise ValueError("Both views must have the same frame dimensions")
            with Image.new("RGB", (2 * a.width, a.height), "white") as combined:
                combined.paste(a, (0, 0))
                combined.paste(b, (a.width, 0))
                path = directory / f"frame_{index:05d}.png"
                combined.save(path)
        paths.append(path)
        if index == 0 or (index + 1) % 30 == 0 or index == len(left) - 1:
            print(f"Combined PNG: {index + 1:4d}/{len(left)} frames", flush=True)
    return paths


def create_gif(paths, destination, *, fps=FPS, size=(GIF_WIDTH, GIF_HEIGHT)):
    """Use one palette for the whole animation to avoid palette flicker."""
    if not paths:
        raise ValueError("At least one PNG frame is needed")
    if isinstance(fps, bool) or not isinstance(fps, (int, float)) or not 1 <= fps <= 100:
        raise ValueError("GIF frame rate must be between 1 and 100")
    sample_indices = np.unique(np.linspace(0, len(paths) - 1, min(24, len(paths))).astype(int))
    tile_size = (round(150 * size[0] / size[1]), 150)
    sheet = Image.new("RGB", (6 * tile_size[0], 4 * tile_size[1]), "white")
    for sample, index in enumerate(sample_indices):
        with Image.open(paths[int(index)]) as image:
            tile = image.convert("RGB").resize(tile_size, Image.Resampling.LANCZOS)
            sheet.paste(tile, ((sample % 6) * tile_size[0], (sample // 6) * tile_size[1]))
    palette = sheet.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    durations = [10 * (round((i + 1) * 100 / fps) - round(i * 100 / fps)) for i in range(len(paths))]

    def quantized(index):
        with Image.open(paths[index]) as image:
            result = image.convert("RGB").resize(size, Image.Resampling.LANCZOS).quantize(
                palette=palette, dither=Image.Dither.NONE)
        if index == 0 or (index + 1) % 30 == 0 or index == len(paths) - 1:
            print(f"GIF {Path(destination).name}: {index + 1:4d}/{len(paths)} frames encoded", flush=True)
        return result

    first = quantized(0)
    try:
        first.save(destination, save_all=True, append_images=(quantized(i) for i in range(1, len(paths))),
                   duration=durations, loop=0, disposal=2, optimize=False)
    finally:
        first.close()
        palette.close()
        sheet.close()
    return Path(destination)


def main():
    if type(FPS) is not int or not 1 <= FPS <= 100:
        raise ValueError("FPS must be an integer between 1 and 100")
    if not np.isfinite(LOOP_SECONDS) or LOOP_SECONDS <= 0:
        raise ValueError("LOOP_SECONDS must be finite and positive")
    if type(DEVELOPMENT_CYCLES) is not int or DEVELOPMENT_CYCLES < 1:
        raise ValueError("DEVELOPMENT_CYCLES must be a positive integer")
    if type(CAMERA_ORBITS) is not int or CAMERA_ORBITS < 1:
        raise ValueError("CAMERA_ORBITS must be a positive integer")
    if not np.isfinite(HOLD_SECONDS) or not 0 <= 2 * HOLD_SECONDS < LOOP_SECONDS / DEVELOPMENT_CYCLES:
        raise ValueError("HOLD_SECONDS must be nonnegative and leave time for development")
    if not np.isfinite(FOLLOW_DISTANCE) or FOLLOW_DISTANCE <= 0:
        raise ValueError("FOLLOW_DISTANCE must be finite and positive")
    if not np.isfinite(FOLLOW_ANGLE_DEGREES) or not -60 <= FOLLOW_ANGLE_DEGREES <= 60:
        raise ValueError("FOLLOW_ANGLE_DEGREES must be between -60 and 60")
    spline, error = fitted_boundaries(FIT_TOLERANCE)
    print(f"Cubic boundary fit: {len(spline.c)} controls per boundary, "
          f"{4 * len(spline.c)} surface controls total; maximum checked error {error:.3g}.", flush=True)
    figure = make_figure()
    original_camera = dict(figure.camera)
    if SHOW_VISUALIZER:
        print("Opening the visualizer. Close its window to begin PNG/GIF export.", flush=True)
        figure.show()
    if not EXPORT_ANIMATION:
        print("EXPORT_ANIMATION=False: no frames or GIF were created.", flush=True)
        return None
    OUTPUT.mkdir(parents=True, exist_ok=True)
    figure.to_yaml(OUTPUT / "completed_view.yaml")
    # Keep a closing PNG for verification; the GIF excludes the duplicate so
    # each intentional hold keeps exactly its configured duration.
    intervals = max(2, round(total_seconds() * FPS))
    count = intervals + 1
    if figure.camera["projection"] != "3d":
        figure.set_camera(**original_camera)
    camera = dict(figure.camera)
    following = figure.copy()
    following.title = "Oloid: following the generating line"
    for name in following.names:
        following.update(name, display={"grid": False})
    following_camera(following, 1.)
    following.to_yaml(OUTPUT / "completed_following_view.yaml")
    start = perf_counter()
    print(f"Exporting {count:,} PNGs per view and three GIFs at {FPS} fps "
          f"({total_seconds():g} seconds; {HOLD_SECONDS:g}-second holds).", flush=True)

    def export_view(view, current):
        view_start = perf_counter()

        def report(index, path):
            elapsed = perf_counter() - view_start
            eta = elapsed / index * (count - index)
            seconds = total_seconds() * (index - 1) / (count - 1)
            _, phase, _ = phase_at(seconds)
            print(f"{view:9s} PNG {index:4d}/{count} ({index/count:6.1%}) | {phase:26s} | "
                  f"elapsed {_clock(elapsed)} | ETA {_clock(eta)} | {path.name}", flush=True)

        paths = current.saveframes(animation_frames(current, camera, count, view=view),
                                   OUTPUT / view / "frames", width=IMAGE_WIDTH, height=IMAGE_HEIGHT,
                                   progress=report)
        current.to_yaml(OUTPUT / ("loop_view.yaml" if view == "overview" else "loop_following_view.yaml"))
        return paths

    overview_paths = export_view("overview", figure)
    overview_gif = create_gif(overview_paths[:-1], OUTPUT / "oloid_overview.gif", fps=FPS,
                              size=(GIF_WIDTH, GIF_HEIGHT))
    following_paths = export_view("following", following)
    following_gif = create_gif(following_paths[:-1], OUTPUT / "oloid_following.gif", fps=FPS,
                               size=(GIF_WIDTH, GIF_HEIGHT))
    paths = combine_frames(overview_paths, following_paths, OUTPUT / "frames")
    combined_gif = create_gif(paths[:-1], OUTPUT / "oloid.gif", fps=FPS, size=(2 * GIF_WIDTH, GIF_HEIGHT))
    for destination in (overview_gif, following_gif, combined_gif):
        print(f"Saved {destination} ({destination.stat().st_size/1024**2:.1f} MiB).", flush=True)
    print(f"Total elapsed {_clock(perf_counter()-start)}.", flush=True)
    return combined_gif


if __name__ == "__main__":
    main()
